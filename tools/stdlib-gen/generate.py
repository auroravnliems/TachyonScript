FLAGS_THREADING = {'entity': 'ENTITY', 'region': 'REGION', 'global': 'GLOBAL', 'async': 'ASYNC'}
FLAGS_EFFECT = {'pure': 'PURE', 'reads': 'READS_WORLD', 'modifies': 'MODIFIES_WORLD', 'io': 'IO'}


def split_doc(text):
    if ' : ' in text:
        head, doc = text.split(' : ', 1)
        return head.strip(), doc.strip()
    return text.strip(), ''


def parse_member(keyword, text, where, owner_override=None):
    head, doc = split_doc(text)
    m = re.match(r'([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)', head)
    if not m:
        fail(where, 'expected a name: ' + head)
    path = m.group(1)
    rest = head[m.end():]
    params = []
    if keyword == 'fn':
        if not rest.startswith('('):
            fail(where, 'expected ( after the function name')
        close = matching(rest, 0)
        for p in split_top(rest[1:close]):
            if ':' not in p:
                fail(where, 'parameter without type: ' + p)
            pname, ptype = p.split(':', 1)
            pname = pname.strip()
            if pname in JAVA_KEYWORDS or pname in RESERVED_LOCALS:
                fail(where, 'parameter name ' + pname + ' is reserved in the generated Java')
            params.append(Param(pname, TypeRef(ptype)))
        rest = rest[close + 1:]
    type_text = 'void'
    rest = rest.strip()
    if rest.startswith(':'):
        type_text, end = parse_type_text(rest, 1)
        rest = rest[end:]
    elif keyword == 'prop':
        fail(where, 'a property needs a type')
    words = rest.split()
    static = 'static' in words
    if owner_override is not None:
        owner, name = owner_override, path
    elif '.' in path and path.rsplit('.', 1)[0] in TYPES and not static:
        owner, name = path.rsplit('.', 1)
    else:
        owner, name = None, path
    member = Member(keyword, owner, name, params, TypeRef(type_text), where, doc=doc)
    for word in words:
        flag = re.match(r'^(entity|region|global|async)(?:\((\w+)\))?$', word)
        if word == 'static':
            continue
        if word == 'rw':
            member.mutable = True
        elif flag:
            member.threading = FLAGS_THREADING[flag.group(1)]
            member.thread_param = flag.group(2)
        elif word in FLAGS_EFFECT:
            member.effect = FLAGS_EFFECT[word]
        else:
            fail(where, 'unknown flag ' + word)
    member.type.check(where)
    for p in params:
        p.type.check(where)
    if member.thread_param is not None and member.thread_param not in [p.name for p in params]:
        fail(where, 'threading parameter ' + member.thread_param + ' is not a parameter')
    if member.threading in ('ENTITY', 'REGION') and owner is None and member.thread_param is None:
        fail(where, 'a global needs a parameter for ' + member.threading.lower() + ' threading')
    if keyword == 'prop' and member.thread_param is not None:
        fail(where, 'properties cannot name a threading parameter')
    return member


def parse_type_line(text, where, area):
    head, doc = split_doc(text[5:])
    if ' = ' not in head:
        fail(where, 'a type needs = <java class>')
    decl, java = head.split(' = ', 1)
    words = decl.split()
    name = words[0]
    if name in TYPES:
        fail(where, 'type ' + name + ' is already declared')
    info = TypeInfo(name, 'GeneratedTypes.' + upper_snake(name), java.strip(), doc=doc, where=where)
    i = 1
    while i < len(words):
        word = words[i]
        if word == 'extends':
            i += 1
            info.supertypes = [s for s in words[i].split(',') if s]
        elif word == 'storable':
            info.storable = True
        elif word == 'core':
            info.core = True
        elif word.startswith('keyed='):
            info.keyed = word[6:]
        elif word.startswith('lookup='):
            info.lookup = word[7:]
        else:
            fail(where, 'unknown type option ' + word)
        i += 1
    for s in info.supertypes:
        if s not in TYPES:
            fail(where, 'unknown supertype ' + s + ' (declare supertypes first)')
    if bool(info.keyed) != bool(info.lookup):
        fail(where, 'a keyed type needs both keyed= and lookup=')
    TYPES[name] = info
    if area is not None:
        area.types.append(info)
    return info


def read_specs():
    areas, imports = [], []
    files = sorted(f for f in os.listdir(SPEC_DIR) if f.endswith('.api'))
    for spec in files:
        with open(os.path.join(SPEC_DIR, spec), encoding='utf-8') as source:
            lines = source.read().split('\n')
        area = None
        target = None          # declaration receiving indented lines
        event = None           # event receiving indented var/prop/fn lines
        for number, raw in enumerate(lines, 1):
            where = f'{spec}:{number}'
            if not raw.strip() or raw.lstrip().startswith('#'):
                continue
            text = raw.strip()
            if not raw.startswith(' '):
                target, event = None, None
                if text.startswith('import '):
                    imports.append((text[7:].strip(), where))
                elif text.startswith('area '):
                    words = text.split()
                    area = Area(words[1], 'core' in words[2:])
                    areas.append(area)
                elif area is None:
                    fail(where, 'declarations must follow an area line')
                elif text.startswith('type '):
                    target = parse_type_line(text, where, area)
                elif text.startswith('prop ') or text.startswith('fn '):
                    keyword, rest = text.split(' ', 1)
                    target = parse_member(keyword, rest, where)
                    area.members.append(target)
                elif text.startswith('event '):
                    head, doc = split_doc(text[6:])
                    if ' = ' not in head:
                        fail(where, 'an event needs = <java class>')
                    name, rest = head.split(' = ', 1)
                    words = rest.split()
                    java = words[0]
                    event = Event(name.strip(), java, java.rsplit('.', 1)[1], where, doc=doc)
                    supertype = None
                    i = 1
                    while i < len(words):
                        word = words[i]
                        if word == 'cancellable':
                            event.cancellable = True
                        elif word == 'extends':
                            i += 1
                            supertype = words[i]
                        elif word in FLAGS_THREADING:
                            event.threading = FLAGS_THREADING[word]
                        else:
                            fail(where, 'unknown event option ' + word)
                        i += 1
                    if event.type_name not in TYPES:
                        supers = []
                        if supertype:
                            if supertype not in TYPES:
                                fail(where, 'unknown supertype ' + supertype)
                            supers.append(supertype)
                        if event.cancellable and not any(is_subtype(s, 'Cancellable') for s in supers):
                            supers.insert(0, 'Cancellable')
                        TYPES[event.type_name] = TypeInfo(event.type_name, 'GeneratedTypes.' + upper_snake(event.type_name),
                                                          java, supertypes=supers, where=where,
                                                          doc='The event object of ' + event.name + ' handlers.')
                        area.types.append(TYPES[event.type_name])
                    elif supertype:
                        fail(where, 'event type ' + event.type_name + ' already exists; cannot extend it here')
                    area.events.append(event)
                    target = event
                else:
                    fail(where, 'unknown directive: ' + text)
                continue
            # Indented lines.
            key = text.split(':', 1)[0] if ':' in text else ''
            if key in ('get', 'set', 'do', 'codec', 'ex', 'details'):
                value = text.split(':', 1)[1].strip()
                indent = len(raw) - len(raw.lstrip(' '))
                if event is not None and indent <= 2 and key in ('ex', 'details'):
                    target = event
                if target is None:
                    fail(where, key + ': without a declaration')
                if key == 'ex':
                    target.examples.append(value.replace('\\n', '\n'))
                elif key == 'details':
                    target.details = (target.details + ' ' + value).strip()
                elif key == 'codec':
                    if not isinstance(target, TypeInfo):
                        fail(where, 'codec: belongs to a type')
                    target.codec = value
                else:
                    if not isinstance(target, Member):
                        fail(where, key + ': belongs to a property or function')
                    setattr(target, 'body' if key == 'do' else key, value)
                continue
            if event is None:
                fail(where, 'unexpected indented line: ' + text)
            if text.startswith('var '):
                head, doc = split_doc(text[4:])
                if ' = ' not in head:
                    fail(where, 'an event variable needs = <expression>')
                decl, expr = head.split(' = ', 1)
                name, type_text = decl.split(':', 1)
                var = EventVar(name.strip(), TypeRef(type_text), expr.strip(), doc)
                var.type.check(where)
                event.vars.append(var)
                target = event
            elif text.startswith('prop ') or text.startswith('fn '):
                keyword, rest = text.split(' ', 1)
                target = parse_member(keyword, rest, where, owner_override=event.type_name)
                area.members.append(target)
            else:
                fail(where, 'unexpected line in an event: ' + text)
    return areas, imports


# ============================================================================ checks

def check(areas):
    names = {}
    for area in areas:
        for m in area.members:
            if m.kind == 'prop' and m.get is None:
                fail(m.where, 'property without get:')
            if m.kind == 'prop' and m.mutable and m.set is None:
                fail(m.where, 'writable property without set:')
            if m.kind == 'prop' and not m.mutable and m.set is not None:
                fail(m.where, 'set: on a read-only property (add rw)')
            if m.kind == 'fn' and m.body is None:
                fail(m.where, 'function without do:')
            if area.core:
                used = [m.type] + [p.type for p in m.params] + ([TypeRef(m.owner)] if m.owner else [])
                for t in used:
                    b = t.base
                    if b in TYPES and not TYPES[b].core:
                        fail(m.where, 'core areas can only use core types, not ' + b)
            if m.owner and m.owner not in TYPES:
                fail(m.where, 'unknown owner ' + m.owner)
            other_kind = 'fn' if m.kind == 'prop' else 'prop'
            for (owner, name, kind, _), where in names.items():
                if owner == m.owner and name == m.name and kind == other_kind:
                    fail(m.where, m.name + ' is both a property and a function (see ' + where + ')')
            signature = (m.owner, m.name, m.kind, tuple(p.type.text for p in m.params))
            if signature in names:
                fail(m.where, 'duplicate of ' + names[signature])
            names[signature] = m.where
        for e in area.events:
            if area.core:
                fail(e.where, 'core areas cannot declare events')


