def upper_snake(name):
    name = name.replace('.', '_')
    out = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', name)
    return re.sub(r'__+', '_', out).upper()


def is_subtype(name, ancestor):
    if name == ancestor:
        return True
    info = TYPES.get(name)
    return info is not None and any(is_subtype(s, ancestor) for s in info.supertypes)


def split_top(text, separator=','):
    """Splits at separators outside <...> and (...)."""
    parts, depth, current = [], 0, ''
    for c in text:
        if c in '<(':
            depth += 1
        elif c in '>)':
            depth -= 1
        if c == separator and depth == 0:
            parts.append(current.strip())
            current = ''
        else:
            current += c
    if current.strip():
        parts.append(current.strip())
    return parts


def matching(text, start):
    """Index of the bracket closing the one at text[start]."""
    opener = text[start]
    closer = {'(': ')', '<': '>', '{': '}'}[opener]
    depth = 0
    for i in range(start, len(text)):
        if text[i] == opener:
            depth += 1
        elif text[i] == closer:
            depth -= 1
            if depth == 0:
                return i
    raise SpecError('Unbalanced brackets: ' + text)


def parse_type_text(text, i=0):
    """Reads a script type at text[i:]; returns (type text, index after it)."""
    while i < len(text) and text[i] == ' ':
        i += 1
    if text.startswith('function(', i):
        close = matching(text, i + len('function'))
        end = close + 1
        j = end
        while j < len(text) and text[j] == ' ':
            j += 1
        if j < len(text) and text[j] == ':':
            _, end = parse_type_text(text, j + 1)
        return text[i:end].strip(), end
    m = re.match(r'[A-Za-z_][A-Za-z0-9_]*', text[i:])
    if not m:
        raise SpecError('Expected a type at: ' + text[i:])
    end = i + m.end()
    if end < len(text) and text[end] == '<':
        end = matching(text, end) + 1
    if end < len(text) and text[end] == '?':
        end += 1
    return text[i:end], end


class TypeRef:
    """A script type used in a specification."""

    def __init__(self, text):
        self.text = text.strip()

    @property
    def nullable(self):
        return self.text.endswith('?') and not self.text.startswith('function(')

    @property
    def base(self):
        return self.text[:-1] if self.nullable else self.text

    def check(self, where):
        try:
            self.constant()
            if self.base != 'void':
                self.java()
        except SpecError as e:
            fail(where, str(e))

    def constant(self):
        if self.nullable:
            return 'Types.nullable(' + TypeRef(self.base).constant() + ')'
        b = self.base
        if b == 'void':
            return 'Types.VOID'
        if b in PRIMITIVES:
            return PRIMITIVES[b][0]
        if b.startswith('List<'):
            return 'Types.list(' + TypeRef(b[5:-1]).constant() + ')'
        if b.startswith('Map<'):
            k, v = split_top(b[4:-1])
            return 'Types.map(' + TypeRef(k).constant() + ', ' + TypeRef(v).constant() + ')'
        if b.startswith('function('):
            close = matching(b, len('function'))
            params = split_top(b[len('function('):close])
            rest = b[close + 1:].strip()
            result = TypeRef(rest[1:]) if rest.startswith(':') else TypeRef('void')
            return ('Types.function(java.util.List.of(' + ', '.join(TypeRef(p).constant() for p in params)
                    + '), ' + result.constant() + ')')
        if b in TYPES:
            return TYPES[b].constant
        raise SpecError('Unknown type ' + b)

    def representation(self):
        if self.nullable:
            return 'REF'
        if self.base == 'void':
            return 'VOID'
        if self.base in PRIMITIVES:
            return PRIMITIVES[self.base][3]
        return 'REF'

    def shape(self):
        return SHAPES[self.representation()]

    def java(self):
        """Java type of values of this type on the platform."""
        b = self.base
        if b in PRIMITIVES:
            return BOXES[b] if self.nullable else PRIMITIVES[b][1]
        if b.startswith('List<'):
            return 'java.util.List<Object>'
        if b.startswith('Map<'):
            return 'java.util.Map<Object, Object>'
        if b.startswith('function('):
            return 'dev.tachyonscript.api.natives.ScriptFunction'
        if b in TYPES and TYPES[b].java:
            return TYPES[b].java
        raise SpecError('Type ' + b + ' has no Java class')

    def read(self, index):
        """Java expression reading argument {index}."""
        if not self.nullable and self.base in PRIMITIVES:
            return 'a.' + PRIMITIVES[self.base][2] + '(' + str(index) + ')'
        java = self.java()
        if java == 'Object':
            return 'a.getRef(' + str(index) + ')'
        if java == 'String':
            return 'a.getString(' + str(index) + ')'
        return '(' + java + ') a.getRef(' + str(index) + ')'


