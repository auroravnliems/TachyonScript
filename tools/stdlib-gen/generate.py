def self_expr(text):
    """Replaces $ (the receiver) with self."""
    return re.sub(r'\$(?![A-Za-z0-9_{])', 'self', text)


def is_block(code):
    code = code.strip()
    return code.startswith('{') and code.endswith('}')


def receiver_lines(member):
    lines = []
    offset = 0
    if member.owner:
        lines.append(TypeRef(member.owner).java() + ' self = ' + TypeRef(member.owner).read(0) + ';')
        offset = 1
    for i, p in enumerate(member.params):
        lines.append(p.type.java() + ' ' + p.name + ' = ' + p.type.read(i + offset) + ';')
    return lines


def wrapped(member, code, returns):
    """Java statements running code on the thread the member requires."""
    code = self_expr(code).strip()
    kind = member.threading
    target = (member.thread_param or 'self') if kind in ('ENTITY', 'REGION') else None
    if kind in ('ENTITY', 'REGION', 'GLOBAL'):
        body = code if is_block(code) else code.rstrip(';')
        if not returns:
            call = {'ENTITY': 'forEntity', 'REGION': 'forRegion', 'GLOBAL': 'global'}[kind]
            return ['ctx.' + call + '(' + (target + ', ' if target else '') + '() -> ' + body + ');']
        if member.effect == 'MODIFIES_WORLD':
            call = {'ENTITY': 'callEntity', 'REGION': 'callRegion', 'GLOBAL': 'callGlobal'}[kind]
            return ['return ctx.' + call + '(' + (target + ', ' if target else '') + '() -> ' + body + ');']
    if is_block(code):
        return [code[1:-1].strip()]
    if returns:
        return ['return ' + code.rstrip(';') + ';']
    return [code if code.endswith(';') else code + ';']


def binding(api, member):
    ref = api + '.' + member.constant
    out = ['        // ' + member.where]
    setup = receiver_lines(member)
    if member.kind == 'prop':
        getter = Member('prop', member.owner, member.name, [], member.type, member.where)
        out.append('        b.bindGetter(' + ref + ', (NativeFunction.' + member.type.shape() + ') a -> {')
        out += ['            ' + line for line in setup]
        out += ['            ' + line for line in wrapped(getter, member.get, True)]
        out.append('        });')
        if member.mutable:
            index = 1 if member.owner else 0
            out.append('        b.bindSetter(' + ref + ', a -> {')
            out += ['            ' + line for line in setup]
            out.append('            ' + member.type.java() + ' v = ' + member.type.read(index) + ';')
            out += ['            ' + line for line in wrapped(member, member.set, False)]
            out.append('        });')
        return out
    returns = member.type.base != 'void'
    out.append('        b.bind(' + ref + ', (NativeFunction.' + member.type.shape() + ') a -> {')
    out += ['            ' + line for line in setup]
    out += ['            ' + line for line in wrapped(member, member.body, returns)]
    out.append('        });')
    return out


