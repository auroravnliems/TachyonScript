def remove_stale(directory, keep):
    if not os.path.isdir(directory):
        return
    for name in os.listdir(directory):
        if name.endswith('.java') and name not in keep:
            os.remove(os.path.join(directory, name))


def main():
    parser = argparse.ArgumentParser(description='Generates the TachyonScript standard library from its specifications.')
    parser.add_argument('--paper-sources', help='folder with the Paper API sources (org/bukkit/...), for constant tables')
    arguments = parser.parse_args()
    try:
        areas, imports = read_specs()
        check(areas)
        assign_constants(areas)
        simple = {}
        for fqn, where in imports:
            name = fqn.rsplit('.', 1)[1]
            if name in simple and simple[name] != fqn:
                fail(where, 'import ' + fqn + ' clashes with ' + simple[name])
            simple[name] = fqn
        import_list = sorted(set(fqn for fqn, _ in imports))
        keyed = [info for info in TYPES.values() if info.new and info.keyed]
        key_tables = {}
        for info in keyed:
            resource = info.name.lower() + '.txt'
            key_tables[info.name] = resource
            if arguments.paper_sources:
                pairs = extract_keys(info.keyed, arguments.paper_sources)
                if not pairs:
                    fail(info.where, 'no constants found for ' + info.keyed)
                write(os.path.join(KEYS_OUT, resource), ''.join(n + ' ' + k + '\n' for n, k in pairs))
            elif not os.path.exists(os.path.join(KEYS_OUT, resource)):
                fail(info.where, 'no constant table yet; run with --paper-sources')
        ordered = write_types(areas, key_tables)
        for area in areas:
            write_api(area)
            write_bindings(area, import_list)
        write_library(areas, ordered, keyed)
        stdlib_files = {'GeneratedTypes.java', 'GeneratedKeys.java', 'GeneratedLibrary.java'}
        paper_files = {'GeneratedBindings.java'}
        for area in areas:
            stdlib_files.add(area.name + 'Api.java')
            (stdlib_files if area.core else paper_files).add(area.name + 'Bindings.java')
        remove_stale(STDLIB_OUT, stdlib_files)
        remove_stale(PAPER_OUT, paper_files)
    except SpecError as e:
        print('error: ' + str(e), file=sys.stderr)
        return 1
    members = sum(len(a.members) for a in areas)
    events = sum(len(a.events) for a in areas)
    types = sum(1 for t in TYPES.values() if t.new)
    print(f'{len(areas)} areas, {types} types ({len(keyed)} keyed), {members} members, {events} events')
    return 0


