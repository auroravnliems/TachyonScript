def strip_java_comments(text):
    text = re.sub(r'/\*.*?\*/', lambda m: ' ' * len(m.group(0)), text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def enum_constants(text, enum_name=None):
    """(constant, first string argument, '' for null, or None) of an enum in a Java source."""
    text = strip_java_comments(text)
    pattern = r'\benum\s+' + (re.escape(enum_name) if enum_name else r'\w+') + r'\b[^{]*\{'
    m = re.search(pattern, text)
    if not m:
        raise SpecError('No enum ' + (enum_name or '') + ' found')
    i = m.end()
    depth = 0
    constants = []
    current = ''
    while i < len(text):
        c = text[i]
        if c == '"':
            end = text.index('"', i + 1)
            while text[end - 1] == '\\':
                end = text.index('"', end + 1)
            current += text[i:end + 1]
            i = end + 1
            continue
        if c in '({':
            depth += 1
        elif c in ')}':
            if depth == 0:
                constants.append(current)
                break
            depth -= 1
        if depth == 0 and c in ',;':
            constants.append(current)
            current = ''
            if c == ';':
                break
        else:
            current += c
        i += 1
    result = []
    for item in constants:
        item = re.sub(r'@\w+(\([^)]*\))?', '', item).strip()
        m = re.match(r'([A-Z][A-Z0-9_]*)\s*(\((.*))?', item, re.S)
        if not m:
            continue
        args = m.group(3) or ''
        string = re.match(r'\s*"([^"]*)"', args)
        null_first = re.match(r'\s*null\b', args)
        result.append((m.group(1), string.group(1) if string else ('' if null_first else None)))
    return result


def extract_keys(spec, sources):
    kind, _, rest = spec.partition(':')
    if kind == 'list':
        return [(name, 'minecraft:' + name.lower()) for name in rest.split(',')]
    path, _, detail = rest.partition(':' if kind == 'fields' else '#')
    with open(os.path.join(sources, path), encoding='utf-8') as source:
        text = source.read()
    pairs = []
    if kind == 'enum':
        for name, key in enum_constants(text, detail or None):
            if name.startswith('LEGACY_') or key == '':
                continue
            key = key or name.lower()
            pairs.append((name, key if ':' in key else 'minecraft:' + key))
        return pairs
    if kind == 'fields':
        for m in re.finditer(r'\b([A-Z][A-Z0-9_]*)\s*=\s*' + re.escape(detail) + r'\(\s*(?:\d+\s*,\s*)?"([^"]+)"', text):
            key = m.group(2)
            pairs.append((m.group(1), key if ':' in key else 'minecraft:' + key))
        return pairs
    raise SpecError('Unknown key source ' + spec)


def lookup_expression(info):
    kind, _, rest = info.lookup.partition(':')
    if kind == 'enum':
        return 'PaperKeys.enumConstants(' + info.java + '.class)'
    if kind == 'keyed-enum':
        return 'PaperKeys.keyedEnum(' + info.java + '.class)'
    if kind == 'registry':
        return 'PaperKeys.registry(io.papermc.paper.registry.RegistryKey.' + rest + ')'
    raise SpecError(info.where + ': unknown lookup ' + info.lookup)


# ============================================================================ Java output

def java_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def documentation(doc, details, examples):
    return ('new Documentation(' + java_string(doc) + ', ' + java_string(details) + ', List.of('
            + ', '.join(java_string(e) for e in examples) + '), "' + SINCE + '")')


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        with open(path, encoding='utf-8') as old:
            if old.read() == content:
                return
    with open(path, 'w', encoding='utf-8', newline='\n') as out:
        out.write(content)


def assign_constants(areas):
    for area in areas:
        taken = set()
        for event in area.events:
            event.constant = upper_snake(event.name) + '_EVENT'
            taken.add(event.constant)
        for member in area.members:
            base = upper_snake((member.owner + '_' if member.owner else '') + member.name)
            name, n = base, 2
            while name in taken:
                name = base + '_' + str(n)
                n += 1
            taken.add(name)
            member.constant = name


def threading_index(member):
    """Invocable parameter index of the threading target (the receiver is 0 for members)."""
    offset = 1 if member.owner else 0
    if member.thread_param is None:
        return 0
    return offset + [p.name for p in member.params].index(member.thread_param)


def declaration(member):
    doc = '.documentation(' + documentation(member.doc, member.details, member.examples) + ')'
    owner = TYPES[member.owner].constant if member.owner else None
    if member.kind == 'prop':
        text = ('PropertyDeclaration.member(' + owner + ', ' + java_string(member.name) + ', ' if owner
                else 'PropertyDeclaration.global(' + java_string(member.name) + ', ') + member.type.constant() + ')'
        if member.mutable:
            text += '.mutable()'
        if member.threading != 'ANY':
            if member.owner or member.threading in ('GLOBAL', 'ASYNC'):
                text += '.getterThreading(ThreadingRequirement.' + member.threading + ')'
                if member.mutable:
                    text += '.setterThreading(ThreadingRequirement.' + member.threading + ')'
        if member.mutable:
            text += '.setterEffects(Effect.MODIFIES_WORLD)'
        if member.effect and member.effect != 'MODIFIES_WORLD':
            text += '.getterEffects(Effect.' + member.effect + ')'
        return text + '\n            ' + doc + '.build()'
    text = ('FunctionDeclaration.method(' + owner + ', ' + java_string(member.name) + ')' if owner
            else 'FunctionDeclaration.global(' + java_string(member.name) + ')')
    for p in member.params:
        text += '.parameter(' + java_string(p.name) + ', ' + p.type.constant() + ')'
    if member.type.base != 'void':
        text += '.returns(' + member.type.constant() + ')'
    if member.effect:
        text += '.effects(Effect.' + member.effect + ')'
    if member.threading in ('ENTITY', 'REGION'):
        text += '.threading(ThreadingRequirement.' + member.threading + ', ' + str(threading_index(member)) + ')'
    elif member.threading != 'ANY':
        text += '.threading(ThreadingRequirement.' + member.threading + ')'
    return text + '\n            ' + doc + '.build()'


