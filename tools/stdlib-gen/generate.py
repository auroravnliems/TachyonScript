#!/usr/bin/env python3
"""
Generates most of the TachyonScript standard library from compact API specifications.

A specification line declares one type, property, function or event: its script signature,
its documentation, its threading and side effects, and the Java code implementing it on
Paper. From the specifications (tools/stdlib-gen/spec/*.api) this script writes

* the Bukkit-free declarations      tachyon-stdlib/.../stdlib/generated/<Area>Api.java
* the generated types               tachyon-stdlib/.../stdlib/generated/GeneratedTypes.java
* the bindings of "core" areas      tachyon-stdlib/.../stdlib/generated/<Area>Bindings.java
* the Paper bindings                tachyon-platform-paper/.../platform/paper/generated/<Area>Bindings.java
* the constant tables of keyed types (Material, Sound, ...), extracted from the Paper API sources,
                                    tachyon-stdlib/src/main/resources/dev/tachyonscript/stdlib/keys/<type>.txt

The generated files are committed: building TachyonScript never needs Python. Run this script
after editing a specification (the constant tables need the Paper API sources, e.g. from the
paper-api sources jar):

    python tools/stdlib-gen/generate.py --paper-sources <folder with org/bukkit/...>

Without --paper-sources the existing constant tables are kept.

Specification format (one directive per line; lines starting with # are comments):

    import <java.Class>                     Java import for the generated Paper bindings
    area <Name> [core]                      following declarations belong to this area; core areas
                                            are implemented without a server (JDK only)
    type <Name> [extends A,B] [storable] [keyed=<keys>] [lookup=<lookup>] [core] = <java.Class> : <doc>
        codec: <Java expression of a dev.tachyonscript.api.storage.Codec>
    prop <Owner>.<name>: <Type> [rw] [<threading>] [<effect>] : <doc>
        get: <Java expression>              $ is the receiver
        set: <Java statement>               v is the new value
    fn <Owner>.<name>(<a>: <T>, ...)[: <R>] [<threading>] [<effect>] : <doc>
        do: <Java expression, statement, or { block }>
    event <name> = <java.EventClass> [cancellable] [extends <Type>] [<threading>] : <doc>
        var <name>: <Type> = <Java expression> : <doc>
        prop / fn ...                       members of the event object (the owner is implied)
    ...
        ex: <script example>                (\\n for new lines) for the declaration above
        details: <longer documentation>

An owner that is not a type (server, math, ...) declares a global property or function; a
global function named like a type (ItemStack, Vector) reads like a constructor in scripts.
Threading: entity | region | global | async, optionally naming the parameter that decides the
owning thread: entity(target). Effects: pure | reads | modifies | io.
Keys: enum:<path.java>[#Nested] | fields:<path.java>:<factory method> | list:NAME,NAME
Lookups (how a key finds the Paper object): enum | keyed-enum | registry:<RegistryKey constant>
"""

